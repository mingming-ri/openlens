export const STRINGS: Record<UiLang, Strings> = { en, es, zh, ar, hi };

/** Native name of each text language. */
export const NATIVE_NAMES: Record<string, string> = {
  eng: 'English', spa: 'Español', chi_sim: '简体中文', ara: 'العربية', hin: 'हिन्दी',
};

/** "Español (西班牙语)": native name, then the name in the app language. Just the native name when they match. */
export function languageLabel(textCode: string, ui: UiLang): string {
  const native = NATIVE_NAMES[textCode] ?? textCode;
  if (findUiLanguage(ui).textCode === textCode) return native;
  return `${native} (${STRINGS[ui].languageNames[textCode]})`;
}

export interface I18n {
  t: Strings;
  ui: UiLang;
  /** A text language's display name in the current app language. */
  name: (textCode: string) => string;
}

export const makeI18n = (ui: UiLang): I18n => ({ t: STRINGS[ui], ui, name: (code) => languageLabel(code, ui) });

export const I18nContext = createContext<I18n>(makeI18n('en'));
export const useI18n = () => useContext(I18nContext);
