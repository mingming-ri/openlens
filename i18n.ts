export type UiLang = 'en' | 'es' | 'zh' | 'ar' | 'hi';

export interface UiLanguage {
  code: UiLang;
  /** The text language (Tesseract code) that matches this app language. */
  textCode: string;
  speechLang: string;
  dir: 'ltr' | 'rtl';
}

export const UI_LANGUAGES: UiLanguage[] = [
  { code: 'en', textCode: 'eng', speechLang: 'en', dir: 'ltr' },
  { code: 'es', textCode: 'spa', speechLang: 'es', dir: 'ltr' },
  { code: 'zh', textCode: 'chi_sim', speechLang: 'zh', dir: 'ltr' },
  { code: 'ar', textCode: 'ara', speechLang: 'ar', dir: 'rtl' },
  { code: 'hi', textCode: 'hin', speechLang: 'hi', dir: 'ltr' },
];

export const findUiLanguage = (code: string) => UI_LANGUAGES.find((l) => l.code === code) ?? UI_LANGUAGES[0];

/** The device's language if the app speaks it, otherwise English. */
export function deviceUiLang(): UiLang {
  const prefs = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  for (const p of prefs) {
    const base = p?.toLowerCase().split('-')[0];
    const hit = UI_LANGUAGES.find((l) => l.code === base);
    if (hit) return hit.code;
  }
  return 'en';
}

